"""Candidate binding to existing adapters; no startup/API activation.

The supplied context remains independently established input. Host SF scope is a
local correlation token, not a persistent DYNAMIXEL session or physical trust.
Tests supply fake Serial ports and DYNAMIXEL sessions to the existing adapters.
"""

from uuid import uuid4

from app.demo.hardware_contract import BottomValveState
from app.hardware.arduino_serial import ArduinoSerialClient
from app.hardware.sf_bottom_valve import SfBottomValveActuator
from app.hardware.simulated_p1_runner import SimulatedP1Device, SimulationBlocked
from app.hardware.fresh_hardware_observations import observe_current_hardware


class PreparedAdapterDevice(SimulatedP1Device):
    """Reuse command-state bookkeeping while delegating transport to real adapters.

    Construction never connects Arduino or samples/moves SF. Only an explicitly
    injected runner can use this candidate; environment startup remains unchanged.
    It does not certify supplied routes/calibration or protect unwrapped callers.
    """

    def __init__(self, current, arduino, sf_valve):
        if type(arduino) is not ArduinoSerialClient or type(sf_valve) is not SfBottomValveActuator:
            raise TypeError("existing Arduino and SF adapters must be explicit")
        self._arduino = arduino
        self._sf_valve = sf_valve
        self._closed = False
        self._sf_scope = str(uuid4())
        super().__init__(current)

    @property
    def controller_boot_id(self):
        return None if self._closed else self._arduino.controller_boot_id

    @controller_boot_id.setter
    def controller_boot_id(self, value):
        if value != self._arduino.controller_boot_id:
            raise SimulationBlocked("supplied references differ from connected controller boot")

    @property
    def arduino_session_id(self):
        if self._closed or not self._arduino.connected:
            return None
        return self._arduino.backend_session_nonce, self._arduino.connection_epoch

    @arduino_session_id.setter
    def arduino_session_id(self, value):
        pass  # Base fixture initialization cannot replace the adapter session.

    @property
    def sf_session_id(self):
        return None if self._closed else self._sf_scope

    @sf_session_id.setter
    def sf_session_id(self, value):
        pass  # Host-only scope is independently generated by this composition.

    def execute(self, **values):
        if self._closed:
            raise SimulationBlocked("adapter composition is closed")
        self.before_send(values)
        self.calls.append(values)
        return self._arduino.execute(**values)

    def observe_before_execution(self, required_commands):
        """Caller must hold the existing sequence owner and operation gate."""
        identity = self.arduino_session_id, self.controller_boot_id
        result = observe_current_hardware(
            self._arduino,
            self._sf_valve,
            required_commands=required_commands or frozenset({"SF_MIXER_SET_STATE"}),
        )
        if identity != (self.arduino_session_id, self.controller_boot_id):
            raise SimulationBlocked("controller session changed during execution preflight")
        return result

    def execute_sf(self, **values):
        if self._closed:
            raise SimulationBlocked("adapter composition is closed")
        self.before_sf_send(values)
        self.sf_calls.append(values)
        self._sf_valve.set_state(BottomValveState(values["state"]))

    def close(self):
        self._closed = True
