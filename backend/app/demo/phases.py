from enum import StrEnum


class RunPhase(StrEnum):
    READY = "READY"
    P1_TRANSFER_S_TO_REACTOR = "P1_TRANSFER_S_TO_REACTOR"
    P1_TRANSFER_FIRST_LIQUID_TO_REACTOR = "P1_TRANSFER_FIRST_LIQUID_TO_REACTOR"
    DELAY_BETWEEN_ADDITIONS = "DELAY_BETWEEN_ADDITIONS"
    P1_TRANSFER_SECOND_LIQUID_TO_REACTOR = "P1_TRANSFER_SECOND_LIQUID_TO_REACTOR"
    REACTION_HOLD = "REACTION_HOLD"
    P2_TRANSFER_REACTOR_TO_SF = "P2_TRANSFER_REACTOR_TO_SF"
    SF_MIXING = "SF_MIXING"
    SF_SETTLING = "SF_SETTLING"
    P2_TRANSFER_SF_TO_COLUMN = "P2_TRANSFER_SF_TO_COLUMN"
    COLUMN_FRACTION_COLLECTION = "COLUMN_FRACTION_COLLECTION"
    COMPLETED = "COMPLETED"


HARDWARE_EXECUTION_PHASES = frozenset(
    {
        RunPhase.P1_TRANSFER_S_TO_REACTOR,
        RunPhase.P1_TRANSFER_FIRST_LIQUID_TO_REACTOR,
        RunPhase.P1_TRANSFER_SECOND_LIQUID_TO_REACTOR,
        RunPhase.P2_TRANSFER_REACTOR_TO_SF,
        RunPhase.P2_TRANSFER_SF_TO_COLUMN,
        RunPhase.COLUMN_FRACTION_COLLECTION,
    }
)


PAUSABLE_EXECUTION_PHASES = frozenset({RunPhase.DELAY_BETWEEN_ADDITIONS, RunPhase.REACTION_HOLD})


# Lifecycle intent support is broader than legacy phase-executor support.
# Adding an intent does not activate a command API or the legacy executor.
EXECUTION_INTENT_PHASES = (
    PAUSABLE_EXECUTION_PHASES
    | HARDWARE_EXECUTION_PHASES
    | frozenset({RunPhase.SF_MIXING, RunPhase.SF_SETTLING})
)
